def get_system_prompt(
    plan: Optional[str] = "sense",
    scene_type: Optional[str] = "battle_turn",
    compact: bool = True,
    p_idol_id: Optional[int] = None,
) -> str:
    """
    Selects or generates an appropriately scoped system prompt.
    Supports plan, scene_type, and optional P-Idol strategy guide filtering.
    In compact mode, returns <= 80 tokens.
    """
    plan_lower = (plan or "sense").lower()
    scene = scene_type or "battle_turn"

    idol_block = ""
    if not compact:
        from demo.core.idol_guides import (
            format_idol_system_snippet,
            get_p_idol_guide,
            resolve_p_idol_id,
        )

        resolved_pid = resolve_p_idol_id(plan=plan_lower, p_idol_id=p_idol_id)
        idol_guide = get_p_idol_guide(resolved_pid)
        if idol_guide is not None:
            idol_block = f"\n\n{format_idol_system_snippet(idol_guide)}"

    if scene == "produce_schedule" or (not compact and scene in ("produce_event", "shop", "popup")):
        return (f"{PRODUCE_SCHEDULE_PROMPT}{idol_block}") if not compact else f"{JSON_OUTPUT_CONSTRAINT}\n{PRODUCE_SCHEDULE_STRATEGY}"
    elif scene == "card_reward":
        return (f"{CARD_REWARD_PROMPT}{idol_block}") if not compact else f"{JSON_OUTPUT_CONSTRAINT}\n{CARD_REWARD_STRATEGY}"

    # Battle turn scene
    if not compact:
        if "sense" in plan_lower:
            return f"{SENSE_SYSTEM_PROMPT}{idol_block}"
        elif "logic" in plan_lower:
            return f"{LOGIC_SYSTEM_PROMPT}{idol_block}"
        elif "anomaly" in plan_lower:
            return f"{ANOMALY_SYSTEM_PROMPT}{idol_block}"
        return f"{DEFAULT_SYSTEM_PROMPT}{idol_block}"

    # Compact dynamic assembly (target <= 80 tokens)
    parts = [JSON_OUTPUT_CONSTRAINT]
    if "sense" in plan_lower:
        parts.append(SENSE_STRATEGY)
    elif "logic" in plan_lower:
        parts.append(LOGIC_STRATEGY)
    elif "anomaly" in plan_lower:
        parts.append(ANOMALY_STRATEGY)
    else:
        parts.extend([SENSE_STRATEGY, LOGIC_STRATEGY, ANOMALY_STRATEGY])

    return "\n".join(parts)


